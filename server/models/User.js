const mongoose = require('mongoose');
const bcrypt = require('bcryptjs');

const UserSchema = new mongoose.Schema({
  name: { type: String, required: true },
  email: { type: String, required: true, unique: true, lowercase: true, trim: true },
  password: { type: String, required: true },
  role: { 
    type: String, 
    enum: ['Customer', 'Staff', 'Manager'], 
    default: 'Customer' 
  }
}, { timestamps: true });

// 🔒 CRUCIAL CIA INTEGRITY RULE: Hash passwords automatically before writing to disk
// FIXED: Removed 'next' callback parameter to align with async/await Promise standards
UserSchema.pre('save', async function () {
  if (!this.isModified('password')) return;
  
  const salt = await bcrypt.genSalt(10);
  this.password = await bcrypt.hash(this.password, salt);
});

// Helper instance method to verify passwords during login lookups
UserSchema.methods.matchPassword = async function (enteredPassword) {
  return await bcrypt.compare(enteredPassword, this.password);
};

module.exports = mongoose.model('User', UserSchema);
